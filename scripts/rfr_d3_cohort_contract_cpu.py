"""RFR-D3 prospective grammar and protocol audits (NO rendered examples).

Pure, Python-standard-library-only contract functions. Inputs are in-memory
metadata declarations supplied by callers, never generated by this module.
There is no prompt construction, corpus/split assignment, model, tokenizer,
file I/O, randomized sampling, evaluation, or provenance promotion.

Public functions:
  audit_grammar_definitions(grammars)
  audit_root_lineage(families, lineage)
  audit_event_declaration(root, arm, readout, declaration)
  audit_matched_contrasts(root, declarations)
  audit_d2_plan_bridge(families, variants, grammars, lineage)

The last function delegates all 8-stratum/27-cell validation to the frozen
D2 module rather than reimplementing its validators. All success reports are
STATIC/PLAN only and explicitly leave realized-cohort gates NOT_EVALUATED.
"""

from collections.abc import Mapping

DOMAINS = frozenset(("REGISTRY_RECORD", "INSTRUMENT_LOG"))
ARMS = frozenset(("VALID_FLIP", "VALID_SHAM", "INVALID_FLIP"))
READOUTS = frozenset(("PRE", "POST", "DELAYED"))
QUERIES = frozenset(("A", "B", "U"))
EVENT_KEYS = frozenset((
    "event_id", "target", "asserted_value", "source_authenticated",
    "event_time", "source_id", "provenance_id",
))
EVENT_OPTIONAL = frozenset(("oracle_version", "derivation_rule_id"))
GRAMMAR_KEYS = frozenset((
    "surface_domain", "renderer_family_id", "lexical_atoms",
    "template_family_ids", "positive_form_id", "explicit_negative_form_id",
    "absence_form_id", "authenticated_marker_id", "unauthenticated_marker_id",
    "rule_conjunction_form_ids", "presentation_order_ids",
    "query_position_ids", "neutral_distractor_family_ids",
))
LINEAGE_KEYS = frozenset((
    "case_family_id", "split_group_id", "semantic_world_id",
    "root_substream_id", "root_kind",
))
DECLARATION_KEYS = frozenset((
    "query_target", "events", "presentation_order", "visible_sections",
    "sealed_field_names", "distractors",
))
VISIBLE_CORE = frozenset((
    "rule", "records", "authentication", "logical_time", "query",
))
SEALED_REQUIRED = frozenset((
    "case_family_id", "split_group_id", "update_arm", "readout_time",
    "query_target", "target_status", "final_label", "final_label_id",
))
VISIBLE_FORBIDDEN = frozenset((
    "case_id", "case_family_id", "split_group_id", "semantic_world_id",
    "initial_A", "initial_C", "initial_U", "root_initial_A",
    "root_initial_C", "root_initial_U", "update_arm", "split",
    "target_status", "final_label", "final_label_id", "oracle_version",
    "renderer_family_id", "template_family_id", "root_substream_id",
    "answer", "gold_label", "label_id", "variant_id",
))
NOT_ESTABLISHED = {
    "CONTENT_INDEPENDENCE": "UNVERIFIED",
    "REALIZED_SPLIT_ISOLATION": "NOT_EVALUATED",
    "ACTUAL_LEXICAL_LEAKAGE": "NOT_EVALUATED",
    "ACTUAL_SHORTCUT_PERFORMANCE": "NOT_EVALUATED",
    "MATERIALIZED_COHORT_FEASIBILITY": "NOT_EVALUATED",
    "TOKENIZER_SERIALIZATION": "NOT_EVALUATED",
    "MODEL_EVALUATION": "NOT_EVALUATED",
    "NATIVE_STATE_CAUSAL_MEDIATION": "NOT_ESTABLISHED",
}


def _mapping(value, required, optional=frozenset(), name="mapping"):
    if not isinstance(value, Mapping):
        raise ValueError("INVALID_MAPPING:" + name)
    keys = set(value)
    if not required <= keys or not keys <= required | optional:
        raise ValueError("SCHEMA_MISMATCH:" + name)
    return value


def _text(value, name):
    if type(value) is not str or not value.strip():
        raise ValueError("INVALID_TEXT:" + name)
    return value


def _enum(value, options, name):
    if type(value) is not str or value not in options:
        raise ValueError("INVALID_ENUM:" + name)
    return value


def _sequence(value, name, min_size=1):
    if type(value) not in (tuple, list) or len(value) < min_size:
        raise ValueError("INVALID_SEQUENCE:" + name)
    return value


def _text_sequence(value, name, min_size=1):
    seq = _sequence(value, name, min_size)
    for item in seq:
        _text(item, name)
    if len(set(seq)) != len(seq):
        raise ValueError("DUPLICATE_ENTRY:" + name)
    return tuple(seq)


def _root_minimum(root):
    _mapping(root, frozenset((
        "case_family_id", "split_group_id", "surface_domain",
        "renderer_family_id", "root_initial_A", "root_initial_C",
        "root_initial_U", "derivation_rule_id", "oracle_version",
    )), frozenset(root) if isinstance(root, Mapping) else frozenset(), "root")
    for key in ("case_family_id", "split_group_id", "renderer_family_id"):
        _text(root[key], key)
    _enum(root["surface_domain"], DOMAINS, "surface_domain")
    for key in ("root_initial_A", "root_initial_C", "root_initial_U"):
        if type(root[key]) is not bool:
            raise ValueError("INVALID_ROOT_BOOLEAN:" + key)
    _enum(root["derivation_rule_id"], {"B_AND_A_C"}, "derivation_rule_id")
    _enum(root["oracle_version"], {"RFR_D1_ORACLE_V1"}, "oracle_version")


def audit_grammar_definitions(grammars) -> dict:
    """Validate disjoint *symbolic* grammar inventories, never produce text.

    Exactly one grammar per candidate domain is required. A grammar declares
    identifiers only, not sentence strings, prompts, or semantic labels.
    """
    _sequence(grammars, "grammars", 2)
    if len(grammars) != 2:
        raise ValueError("EXACTLY_TWO_GRAMMARS_REQUIRED")
    domains = set()
    all_lexemes = set()
    all_templates = set()
    all_rule_forms = set()
    all_surface_markers = set()
    renderer_ids = set()
    for grammar in grammars:
        _mapping(grammar, GRAMMAR_KEYS, name="grammar")
        domain = _enum(grammar["surface_domain"], DOMAINS, "surface_domain")
        if domain in domains:
            raise ValueError("DUPLICATE_DOMAIN")
        domains.add(domain)
        renderer = _text(grammar["renderer_family_id"], "renderer_family_id")
        if renderer in renderer_ids:
            raise ValueError("RENDERER_ID_COLLISION")
        renderer_ids.add(renderer)
        lexemes = _text_sequence(grammar["lexical_atoms"], "lexical_atoms", 4)
        templates = _text_sequence(grammar["template_family_ids"], "template_family_ids", 2)
        rules = _text_sequence(grammar["rule_conjunction_form_ids"], "rule_conjunction_form_ids", 2)
        _text_sequence(grammar["presentation_order_ids"], "presentation_order_ids", 2)
        _text_sequence(grammar["query_position_ids"], "query_position_ids", 2)
        _text_sequence(grammar["neutral_distractor_family_ids"], "neutral_distractor_family_ids")
        markers = tuple(_text(grammar[k], k) for k in (
            "positive_form_id", "explicit_negative_form_id", "absence_form_id",
            "authenticated_marker_id", "unauthenticated_marker_id",
        ))
        if len(set(markers)) != len(markers):
            raise ValueError("POLARITY_OR_AUTHENTICATION_CUE_COLLISION")
        reserved = {"support", "refute", "not_entitled", "final_label", "target_status", "gold_label"}
        if any(s.casefold() in reserved for s in lexemes + templates + rules + markers):
            raise ValueError("GOLD_LABEL_LEXICON")
        if set(lexemes) & all_lexemes:
            raise ValueError("CROSS_DOMAIN_LEXICON_COLLISION")
        if set(templates) & all_templates:
            raise ValueError("CROSS_DOMAIN_TEMPLATE_COLLISION")
        if set(rules) & all_rule_forms:
            raise ValueError("CROSS_DOMAIN_RULE_FORM_COLLISION")
        if set(markers) & all_surface_markers:
            raise ValueError("CROSS_DOMAIN_AUTH_POLARITY_FORM_COLLISION")
        all_surface_markers.update(markers)
        all_lexemes.update(lexemes)
        all_templates.update(templates)
        all_rule_forms.update(rules)
    if domains != DOMAINS:
        raise ValueError("MISSING_REQUIRED_DOMAIN")
    return {"status": "PASS_STATIC_CONTRACT", "declared_domain_count": 2,
            "TEXT_RENDERING": "NOT_EVALUATED", **NOT_ESTABLISHED}


def audit_root_lineage(families, lineage) -> dict:
    """Check proposed root ancestry; D2 performs full registry audits separately."""
    _sequence(families, "families")
    _sequence(lineage, "lineage")
    ids = {}
    groups = set()
    for root in families:
        _root_minimum(root)
        fid = root["case_family_id"]
        if fid in ids or root["split_group_id"] in groups:
            raise ValueError("DUPLICATE_ROOT_OR_GROUP")
        ids[fid] = root
        groups.add(root["split_group_id"])
    seen_worlds = set()
    seen_substreams = set()
    seen_lineages = set()
    for item in lineage:
        _mapping(item, LINEAGE_KEYS, name="lineage")
        fid = _text(item["case_family_id"], "case_family_id")
        if fid not in ids or fid in seen_lineages:
            raise ValueError("UNKNOWN_OR_DUPLICATE_LINEAGE")
        seen_lineages.add(fid)
        if item["split_group_id"] != ids[fid]["split_group_id"]:
            raise ValueError("LINEAGE_GROUP_CONFLICT")
        _enum(item["root_kind"], {"PRIMARY_ROOT"}, "root_kind")
        world = _text(item["semantic_world_id"], "semantic_world_id")
        substream = _text(item["root_substream_id"], "root_substream_id")
        if world in seen_worlds or substream in seen_substreams:
            raise ValueError("REUSED_ROOT_WORLD_OR_SUBSTREAM")
        seen_worlds.add(world)
        seen_substreams.add(substream)
    if seen_lineages != set(ids):
        raise ValueError("MISSING_ROOT_LINEAGE")
    return {"status": "PASS_STATIC_CONTRACT", "declared_root_count": len(ids),
            "ROOT_SUBSTREAM_IDENTITY": "DECLARED_ONLY", **NOT_ESTABLISHED}


def _validated_events(root, arm, readout, declaration):
    """Interpret only typed *declarations*; do not generate or evaluate rows."""
    _root_minimum(root)
    _enum(arm, ARMS, "update_arm")
    _enum(readout, READOUTS, "readout_time")
    _mapping(declaration, DECLARATION_KEYS, name="event_declaration")
    _enum(declaration["query_target"], QUERIES, "query_target")
    seq = _sequence(declaration["events"], "events")
    core = {}
    for event in seq:
        _mapping(event, EVENT_KEYS, EVENT_OPTIONAL, "event")
        for field in ("event_id", "source_id", "provenance_id"):
            _text(event[field], field)
        _enum(event["target"], {"A", "C", "U"}, "event_target")
        for field in ("asserted_value", "source_authenticated"):
            if type(event[field]) is not bool:
                raise ValueError("INVALID_EVENT_BOOLEAN:" + field)
        if type(event["event_time"]) is not int:
            raise ValueError("INVALID_EVENT_TIMESTAMP")
        if "oracle_version" in event:
            _enum(event["oracle_version"], {"RFR_D1_ORACLE_V1"}, "oracle_version")
        if "derivation_rule_id" in event:
            _enum(event["derivation_rule_id"], {"B_AND_A_C"}, "derivation_rule_id")
        eid = event["event_id"]
        if eid in core:
            raise ValueError("DUPLICATE_EVENT_ID")
        core[eid] = event
    if len(core) != (3 if readout == "PRE" else 4):
        raise ValueError("EVENT_COUNT_OR_PRE_FUTURE_LEAKAGE")
    initial = {}
    t1 = None
    for event in seq:
        if event["event_time"] == 10 and event["target"] in {"A", "C", "U"}:
            target = event["target"]
            if target in initial or not event["source_authenticated"]:
                raise ValueError("INVALID_INITIAL_AUTHORITY")
            if event["asserted_value"] is not root["root_initial_" + target]:
                raise ValueError("ROOT_TRUTH_CONFLICT")
            initial[target] = event
        elif event["event_time"] == 20 and event["target"] == "A":
            if t1 is not None:
                raise ValueError("DUPLICATE_T1")
            t1 = event
        else:
            raise ValueError("ILLEGAL_EVENT_TARGET_OR_TIME")
    if set(initial) != {"A", "C", "U"}:
        raise ValueError("MISSING_INITIAL_BASE_RECORD")
    if readout == "PRE":
        if t1 is not None:
            raise ValueError("PRE_FUTURE_EVENT_LEAKAGE")
    else:
        if t1 is None:
            raise ValueError("MISSING_T1_EVENT")
        expected = root["root_initial_A"] if arm == "VALID_SHAM" else not root["root_initial_A"]
        if t1["asserted_value"] is not expected:
            raise ValueError("INCORRECT_T1_POLARITY")
        if t1["source_authenticated"] is not (arm != "INVALID_FLIP"):
            raise ValueError("INCORRECT_T1_AUTHENTICATION")
    order = _text_sequence(declaration["presentation_order"], "presentation_order")
    if set(order) != set(core) or len(order) != len(core):
        raise ValueError("PRESENTATION_ORDER_NOT_PERMUTATION")
    visible = _text_sequence(declaration["visible_sections"], "visible_sections")
    allowed_visible = VISIBLE_CORE | ({"neutral_delay"} if readout == "DELAYED" else set())
    if set(visible) != allowed_visible or set(visible) & VISIBLE_FORBIDDEN:
        raise ValueError("VISIBLE_METADATA_OR_REQUIRED_SECTION_VIOLATION")
    sealed = set(_text_sequence(declaration["sealed_field_names"], "sealed_field_names"))
    if not SEALED_REQUIRED <= sealed or sealed & set(visible):
        raise ValueError("SEALED_METADATA_CONTRACT_VIOLATION")
    distractors = _sequence(declaration["distractors"], "distractors", 1 if readout == "DELAYED" else 0)
    if readout != "DELAYED" and distractors:
        raise ValueError("DISTRACTORS_ONLY_DELAYED")
    distractor_ids = set()
    for distractor in distractors:
        _mapping(distractor, {"distractor_id", "kind"}, name="distractor")
        did = _text(distractor["distractor_id"], "distractor_id")
        _enum(distractor["kind"], {"NEUTRAL"}, "distractor_kind")
        if did in distractor_ids:
            raise ValueError("DUPLICATE_DISTRACTOR")
        distractor_ids.add(did)
    return initial, t1


def audit_event_declaration(root, arm, readout, declaration) -> dict:
    """Check one externally declared typed protocol, with no model-visible text."""
    _validated_events(root, arm, readout, declaration)
    return {"status": "PASS_STATIC_CONTRACT",
            "DECLARED_EVENT_PROTOCOL": "PASS_STATIC_CONTRACT",
            "ACTUAL_PRE_INPUT_BYTES": "NOT_EVALUATED", **NOT_ESTABLISHED}


def audit_matched_contrasts(root, declarations) -> dict:
    """Check POST arm contrasts over *declared* event records only.

    `declarations` is exactly {arm: event_declaration}; a shared root, query
    and baseline events must be preserved. This checks neither actual text nor
    correctness of source authentication evidence in rendered prompts.
    """
    _mapping(declarations, ARMS, name="matched_contrasts")
    validated = {arm: _validated_events(root, arm, "POST", declarations[arm])
                 for arm in ARMS}
    queries = {declarations[arm]["query_target"] for arm in ARMS}
    if len(queries) != 1:
        raise ValueError("MATCHED_QUERY_CONFLICT")
    initial = []
    for arm in ARMS:
        records, t1 = validated[arm]
        initial.append(tuple(sorted(tuple(sorted(e.items())) for e in records.values())))
        if t1 is None:
            raise ValueError("MISSING_T1_EVENT")
    if not (initial[0] == initial[1] == initial[2]):
        raise ValueError("MATCHED_BASELINE_CONFLICT")
    flip = validated["VALID_FLIP"][1]
    sham = validated["VALID_SHAM"][1]
    invalid = validated["INVALID_FLIP"][1]
    provenance_keys = {"source_authenticated", "source_id", "provenance_id"}
    if set(flip) != set(invalid) or any(
        flip[key] != invalid[key] for key in flip if key not in provenance_keys
    ):
        raise ValueError("FLIP_INVALID_CONTENT_CONFLICT")
    if (flip["source_id"], flip["provenance_id"]) == (
        invalid["source_id"], invalid["provenance_id"]
    ):
        raise ValueError("FLIP_INVALID_PROVENANCE_NOT_DISTINCT")
    if set(flip) != set(sham) or any(
        flip[key] != sham[key] for key in flip if key != "asserted_value"
    ):
        raise ValueError("FLIP_SHAM_UPDATE_SITE_CONFLICT")
    if flip["asserted_value"] == sham["asserted_value"]:
        raise ValueError("NO_CORRECTION_DIRECTION_CONTRAST")
    return {"status": "PASS_STATIC_CONTRACT", "matched_arm_count": 3,
            "ACTUAL_AUTHENTICATION_EVIDENCE": "NOT_EVALUATED", **NOT_ESTABLISHED}


def audit_d2_plan_bridge(families, variants, grammars, lineage) -> dict:
    """Delegate frozen D2 plan checks; never promote a PASS_PLAN_CHECK.

    The import is deliberately local and deferred. Run this integration path
    inside the original repository with its frozen D2 validator available.
    """
    from scripts import rfr_d2_structural_feasibility_cpu as d2

    grammar = audit_grammar_definitions(grammars)
    lineage_report = audit_root_lineage(families, lineage)
    by_domain = {g["surface_domain"]: g for g in grammars}
    for root in families:
        desc = by_domain[root["surface_domain"]]
        if root["renderer_family_id"] != desc["renderer_family_id"]:
            raise ValueError("ROOT_RENDERER_GRAMMAR_CONFLICT")
    family_report = d2.audit_family_registry(families)
    variant_report = d2.audit_variant_plan(variants, families)
    status = "PASS_STATIC_CONTRACT" if (
        grammar["status"] == "PASS_STATIC_CONTRACT"
        and lineage_report["status"] == "PASS_STATIC_CONTRACT"
        and family_report["status"] == "PASS_PLAN_CHECK"
        and variant_report["status"] == "PASS_PLAN_CHECK"
    ) else "FAIL"
    return {"status": status, "D2_FAMILY_PLAN": family_report["status"],
            "D2_VARIANT_PLAN": variant_report["status"],
            "counted_independent_units": variant_report.get("counted_independent_units", 0),
            "GENERATED_CASE_ROWS": "NONE", **NOT_ESTABLISHED}
